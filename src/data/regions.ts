export interface CountryOption {
  code: string
  name: string
}

const displayNames = new Intl.DisplayNames(['pt-BR'], { type: 'region' })

export function countryName(code: string): string {
  try {
    return displayNames.of(code) ?? code
  } catch {
    return code
  }
}

export function stateName(code: string): string {
  return BRAZIL_STATES.find((state) => state.code === code)?.name ?? code
}

/** Brasil primeiro; os demais em ordem alfabética. */
export const countryOptions: CountryOption[] = COUNTRY_CODES.map((code) => ({ code, name: countryName(code) })).sort(
  (a, b) => {
    if (a.code === BRAZIL) return -1
    if (b.code === BRAZIL) return 1
    return a.name.localeCompare(b.name, 'pt-BR')
  },
)
